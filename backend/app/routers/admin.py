import asyncio
from datetime import datetime, timezone
from typing import List
from fastapi import APIRouter, Depends, HTTPException, Header
from sqlalchemy.orm import Session
from backend.app.database import get_db
from backend.app.models import Stop, Vehicle, DispatchRecommendation, AuditLog
from backend.app.schemas import (
    DemandSummaryItem, RecommendationOut, RecommendationAction
)
from backend.app.services.demand_service import DemandService
from backend.app.services.recommendation_service import RecommendationService
from backend.app.services.connection_manager import manager

router = APIRouter(prefix="/api/admin", tags=["Admin"])

def verify_admin_role(role: str = Header(default="admin")):
    if role != "admin":
        raise HTTPException(status_code=403, detail="Forbidden: Admin role required")
    return role

@router.get("/demand", response_model=List[DemandSummaryItem])
def get_fleet_demand_summary(
    db: Session = Depends(get_db),
    role: str = Depends(verify_admin_role)
):
    """
    Returns demand vs supply comparison for all stops in the current departure window.
    """
    stops = db.query(Stop).order_by(Stop.sequence_hint.asc()).all()
    results = []

    for stop in stops:
        # Check active recommendation
        active_rec = db.query(DispatchRecommendation).filter(
            DispatchRecommendation.stop_id == stop.id,
            DispatchRecommendation.status == "pending"
        ).first()

        # If a recommendation was generated with simulated historical demand, reflect that
        simulated_hist = active_rec.demand - active_rec.free_capacity if (active_rec and active_rec.shortfall > 0) else 0
        data = DemandService.calculate_stop_demand_and_supply(db, stop.id, simulated_historical_demand=max(0, simulated_hist))

        results.append(DemandSummaryItem(
            stop_id=stop.id,
            stop_name=stop.name,
            window="16:00 - 16:15",
            confirmed_intents=data["confirmed_intents"],
            historical_estimate=data["historical_estimate"],
            total_expected_demand=data["total_demand"],
            scheduled_free_capacity=data["free_capacity"],
            shortfall=data["shortfall"],
            has_active_recommendation=active_rec is not None
        ))

    return results

@router.get("/recommendations", response_model=List[RecommendationOut])
def get_recommendations(
    db: Session = Depends(get_db),
    role: str = Depends(verify_admin_role)
):
    """List all dispatch recommendations generated by rule engine."""
    recs = db.query(DispatchRecommendation).order_by(DispatchRecommendation.created_at.desc()).all()
    out = []
    for r in recs:
        stop = db.query(Stop).filter(Stop.id == r.stop_id).first()
        veh = db.query(Vehicle).filter(Vehicle.id == r.suggested_vehicle_id).first() if r.suggested_vehicle_id else None
        out.append(RecommendationOut(
            id=r.id,
            stop_id=r.stop_id,
            stop_name=stop.name if stop else r.stop_id,
            window=r.window,
            demand=r.demand,
            free_capacity=r.free_capacity,
            shortfall=r.shortfall,
            suggested_vehicle_id=r.suggested_vehicle_id,
            suggested_vehicle_label=veh.label if veh else None,
            suggestion=r.suggestion,
            status=r.status,
            reason=r.reason,
            created_at=r.created_at,
            actioned_at=r.actioned_at
        ))
    return out

@router.post("/recommendations/action", response_model=RecommendationOut)
async def action_recommendation(
    action_in: RecommendationAction,
    db: Session = Depends(get_db),
    role: str = Depends(verify_admin_role)
):
    """
    Accept or reject a dispatch recommendation and log audit trail (FR-11, FR-16).
    """
    try:
        rec = RecommendationService.action_recommendation(
            db=db,
            recommendation_id=action_in.recommendation_id,
            action=action_in.action,
            actor="admin_lead",
            reason=action_in.reason
        )
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))

    stop = db.query(Stop).filter(Stop.id == rec.stop_id).first()
    veh = db.query(Vehicle).filter(Vehicle.id == rec.suggested_vehicle_id).first() if rec.suggested_vehicle_id else None

    # Broadcast recommendation status update
    asyncio.create_task(manager.broadcast({
        "type": "RECOMMENDATION_ACTIONED",
        "id": rec.id,
        "status": rec.status,
        "stop_name": stop.name if stop else rec.stop_id,
        "timestamp": datetime.now(timezone.utc).isoformat()
    }))

    return RecommendationOut(
        id=rec.id,
        stop_id=rec.stop_id,
        stop_name=stop.name if stop else rec.stop_id,
        window=rec.window,
        demand=rec.demand,
        free_capacity=rec.free_capacity,
        shortfall=rec.shortfall,
        suggested_vehicle_id=rec.suggested_vehicle_id,
        suggested_vehicle_label=veh.label if veh else None,
        suggestion=rec.suggestion,
        status=rec.status,
        reason=rec.reason,
        created_at=rec.created_at,
        actioned_at=rec.actioned_at
    )

@router.get("/audit-logs")
def get_audit_logs(
    db: Session = Depends(get_db),
    role: str = Depends(verify_admin_role)
):
    """Returns chronologically recorded audit trail (FR-16)."""
    return db.query(AuditLog).order_by(AuditLog.timestamp.desc()).limit(100).all()
